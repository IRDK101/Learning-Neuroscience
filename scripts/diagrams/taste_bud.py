"""Generates content/diagrams/taste-bud.svg: a taste bud in the tongue's epithelium, with a papilla inset."""
import math
from pathlib import Path
from curves import smooth, blob, f, taper, spindle, bow, sample

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/taste-bud.svg'
CX = 440

# ---- epithelium: surface dips into the taste pore at CX
surface = [(150, 112), (230, 106), (320, 104), (392, 108), (414, 114), (426, 132), (CX, 142), (454, 132), (466, 114),
           (488, 108), (560, 104), (650, 106), (730, 112)]
epi = smooth(surface) + ' L 730 420 L 150 420 Z'
pore = smooth([(414, 114), (426, 132), (CX, 142), (454, 132), (466, 114)]) + ' C 452 110 428 110 414 114 Z'

# ---- the bud: onion-shaped outline
bud_pts = [(CX, 138), (486, 160), (522, 220), (536, 300), (520, 370), (480, 404), (CX, 410), (400, 404), (360, 370),
           (344, 300), (358, 220), (394, 160)]
bud = smooth(bud_pts, closed=True)

# ---- taste cells: spindles from the base to the pore, fanning out
cells, nuclei, villi, vesicles = [], [], [], []
offs = [-96, -72, -48, -24, 0, 24, 48, 72, 96]
for k, o in enumerate(offs):
    base = (CX + o * 0.9, 398 - abs(o) * 0.3 - (o / 30) ** 2 * 1.5)
    top = (CX + o * 0.1, 150)
    line = bow(base, top, o * 0.34, n=9)
    w = 22 if abs(o) < 80 else 17
    cells.append(f'<path d="{spindle(line, w, 4)}"/>')
    mx, my = line[3 + (k % 2)]
    nuclei.append(f'<ellipse cx="{f(mx)}" cy="{f(my)}" rx="{f(w * 0.26)}" ry="{f(w * 0.5)}" transform="rotate({f(math.degrees(math.atan2(line[6][0] - line[4][0], line[4][1] - line[6][1])))} {f(mx)} {f(my)})"/>')
    tx, ty = top
    for j in (-3, 0, 3):
        villi.append(f'M {f(tx + j * 0.7)} {f(ty + 2)} L {f(tx + j * 1.6)} {f(ty - 12)}')
    bx, by = line[1]
    for dx, dy in ((-3, -2), (3, 1), (0, 5)):
        vesicles.append(f'<circle cx="{f(bx + dx)}" cy="{f(by + dy - 6)}" r="2"/>')

basal = ''.join(f'<path d="{blob(x, y, 13, 9, 0.08, seed=i, rot=r)}"/>' for i, (x, y, r) in enumerate([(372, 368, 30), (412, 396, 5), (468, 396, -5), (508, 368, -30)]))
basal_nuc = ''.join(f'<circle cx="{x}" cy="{y}" r="3.4"/>' for x, y in [(372, 368), (412, 396), (468, 396), (508, 368)])

# ---- gustatory afferent axons: enter from below and branch to the cell bases
axons = []
for x0, targets in [(392, [(370, 392), (392, 396), (414, 400)]), (470, [(440, 404), (466, 400), (490, 396)]), (520, [(508, 384), (522, 372)])]:
    trunk = [(x0 - 10, 500), (x0 - 4, 470), (x0, 440), (x0 + 2, 422)]
    axons.append(taper(trunk, 9, 6))
    for tx, ty in targets:
        axons.append(taper([(x0 + 2, 424), ((x0 + tx) / 2, (424 + ty) / 2 + 4), (tx, ty)], 5, 3))
axon_d = ' '.join(axons)

# ---- epithelial texture: flattened cells near the surface, rounder deeper down
import random
rnd = random.Random(5)
epi_cells = []
for row, y in enumerate(range(126, 412, 22)):
    for x in range(160 + (row % 2) * 18, 726, 36):
        dx = x - CX
        dy = y - 280
        if (dx / 112) ** 2 + (dy / 140) ** 2 < 1.15:
            continue
        flat = max(0.35, min(1.0, (y - 110) / 200))
        rx, ry = 15, 9 * flat + 2
        if y < 140 and abs(dx) < 50:
            continue
        epi_cells.append(f'<ellipse cx="{f(x + rnd.uniform(-3, 3))}" cy="{f(y + rnd.uniform(-2, 2))}" rx="{rx}" ry="{f(ry)}"/>')

# ---- papilla inset (top left): a fungiform-like bump with buds on top, and a circumvallate-like groove
ins_x, ins_y = 20, 150
pap = smooth([(30, 332), (58, 328), (74, 304), (70, 272), (54, 246), (68, 218), (110, 206), (152, 218), (166, 246), (150, 272), (146, 304), (162, 328), (190, 332)])
pap_d = pap + ' L 190 380 L 30 380 Z'
ins_buds = ''.join(f'<ellipse cx="{x}" cy="{y}" rx="6" ry="9" transform="rotate({r} {x} {y})"/>' for x, y, r in [(76, 226, -45), (110, 214, 0), (144, 226, 45)])

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="10 30 830 480" class="shade-sm" role="img" aria-label="A taste bud in the tongue, with a papilla inset">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/taste_bud.py (edit that, not this).
       Stylized; a real taste bud is about 50 micrometers tall. -->
  <defs>
    <clipPath id="tb-clip"><rect x="236" y="60" width="430" height="440"/></clipPath>
    <clipPath id="tb-ins"><rect x="20" y="180" width="180" height="200" rx="10"/></clipPath>
  </defs>
  <g class="base">
    <rect class="deco inset-frame" x="20" y="180" width="180" height="200" rx="10"/>
    <g clip-path="url(#tb-ins)">
      <path class="deco tissue" style="--dc: var(--sys-body)" d="M 20 330 L 200 330 L 200 380 L 20 380 Z"/>
      <path data-ref="papilla" d="{pap_d}"/>
      <g data-ref="taste-bud" data-fill="var(--sys-cellular)">{ins_buds}</g>
    </g>
    <path class="deco zoom-line" d="M 116 212 L 344 160 M 122 228 L 344 380"/>

    <g clip-path="url(#tb-clip)">
      <path class="deco tissue" style="--dc: color-mix(in srgb, var(--sys-body) 55%, var(--bg-elev))" d="M 150 400 L 730 400 L 730 500 L 150 500 Z"/>
      <path class="deco tissue no-shade" style="--dc: color-mix(in srgb, var(--sys-body) 40%, var(--bg-elev))" d="{epi}"/>
      <g class="deco epi-cells">{''.join(epi_cells)}</g>
      <path data-ref="taste-pore" data-fill="#cfe3f2" d="{pore}"/>
      <path data-ref="taste-bud" data-fill="var(--sys-cellular)" data-tone="2" d="{bud}"/>
      <g data-ref="basal-cell" data-fill="#9fb4cf">{basal}</g>
      <g class="deco cell-nuc">{basal_nuc}</g>
      <g data-ref="taste-cell" data-fill="#e4b07a">{''.join(cells)}</g>
      <g class="deco cell-nuc">{''.join(nuclei)}</g>
      <g class="deco vesicle-dots">{''.join(vesicles)}</g>
      <path data-ref="microvilli" class="line-hotspot fine" data-fill="#b0703a" d="{' '.join(villi)}"/>
      <path data-ref="gustatory-afferent-axon" data-fill="var(--sys-nerve)" d="{axon_d}"/>
    </g>

    <g class="labels lbl-base">
      <text data-label-for="papilla" x="34" y="170">Papilla</text>
      <text class="small" data-label-for="taste-bud" x="110" y="400" text-anchor="middle">Taste buds</text>
      <text data-label-for="taste-pore" x="560" y="60">Taste pore</text>
      <line data-label-for="taste-pore" class="leader" x1="558" y1="64" x2="452" y2="124"/>
      <text data-label-for="microvilli" x="560" y="90">Microvilli</text>
      <line data-label-for="microvilli" class="leader" x1="558" y1="94" x2="446" y2="142"/>
      <text data-label-for="taste-cell" x="684" y="210">Taste cell</text>
      <line data-label-for="taste-cell" class="leader" x1="682" y1="206" x2="520" y2="240"/>
      <text data-label-for="taste-bud" x="684" y="300">Taste bud</text>
      <line data-label-for="taste-bud" class="leader" x1="682" y1="296" x2="534" y2="300"/>
      <text data-label-for="basal-cell" x="684" y="370">Basal cell</text>
      <line data-label-for="basal-cell" class="leader" x1="682" y1="366" x2="520" y2="368"/>
      <text data-label-for="gustatory-afferent-axon" x="540" y="476">Gustatory afferent axon</text>
      <line data-label-for="gustatory-afferent-axon" class="leader" x1="538" y1="470" x2="524" y2="456"/>
      <text class="small deco-label" x="244" y="96">Tongue surface</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
