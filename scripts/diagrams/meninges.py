"""Generates content/diagrams/meninges.svg: the layers from the skull down to the white matter, in cross-section.
Layer thicknesses are exaggerated (the real arachnoid and pia are microscopically thin)."""
import math
from pathlib import Path
from curves import smooth, poly_d, f

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/meninges.svg'
X0, X1 = 20, 520

def surface(x, depth=62, crown=24, base=214, period=124, phase=0.12, sharp=5.5):
    """Brain surface height: rounded gyri, narrow sulci."""
    u = ((x - X0) / period + phase) % 1.0
    sn = max(0.0, math.sin(math.pi * u))
    slot = max(0.0, 1 - sn * sharp) ** 1.5          # narrow, deep sulcus at each gyrus edge
    return base - crown * sn ** 0.5 + depth * slot

xs = [X0 + i * 2 for i in range((X1 - X0) // 2 + 1)]
pia = [(x, surface(x)) for x in xs]
white_top = [(x, surface(x, depth=40, crown=16, base=272, sharp=3.2)) for x in xs]

def under(line, bottom=410):
    return poly_d(line + [(X1, bottom), (X0, bottom)])

ARACH = 140
subarach = poly_d([(X0, ARACH), (X1, ARACH)] + list(reversed(pia)))
pia_line = poly_d(pia, closed=False)

# diploë (spongy bone) holes
import random
rnd = random.Random(4)
holes = []
for _ in range(70):
    x, y = rnd.uniform(X0 + 6, X1 - 6), rnd.uniform(44, 72)
    rx, ry = rnd.uniform(3, 8), rnd.uniform(2, 4.5)
    holes.append(f'<ellipse cx="{f(x)}" cy="{f(y)}" rx="{f(rx)}" ry="{f(ry)}"/>')

# arachnoid trabeculae: fine wavy strands from the arachnoid down to the pia
trab = []
for i, x in enumerate(range(X0 + 26, X1, 38)):
    y1 = surface(x + 6) - 2
    if y1 - ARACH < 18:
        continue
    mid = (ARACH + y1) / 2
    trab.append(f"M {x} {ARACH} C {x + 8} {f(mid - 10)} {x - 6} {f(mid + 6)} {x + 6} {f(y1)}")
    trab.append(f"M {x} {f(mid - 4)} L {x + 14} {f(mid - 14)}")

# blood vessels in the subarachnoid space
vessels = []
for cx, cy, r in [(80, 168, 10), (204, 164, 13), (330, 170, 9), (452, 166, 12)]:
    vessels.append(f'<circle cx="{cx}" cy="{cy}" r="{r}"/><circle class="lumen" cx="{cx}" cy="{cy}" r="{r * 0.55:.1f}"/>')

# cortex texture: a few pyramidal-cell dots
rnd = random.Random(9)
cells = []
for _ in range(90):
    x = rnd.uniform(X0 + 4, X1 - 4)
    top, bot = surface(x) + 6, surface(x, depth=40, crown=16, base=272, sharp=3.2) - 4
    if bot - top < 6:
        continue
    y = rnd.uniform(top, bot)
    cells.append(f'<circle cx="{f(x)}" cy="{f(y)}" r="1.6"/>')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 420" class="shade-sm" role="img" aria-label="Cross-section of the layers between the skull and the brain">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/meninges.py (edit that, not this).
       Stylized cross-section, not to scale: the real layers are far thinner. -->
  <defs>
    <clipPath id="men-clip"><rect x="{X0}" y="0" width="{X1 - X0}" height="420" rx="6"/></clipPath>
  </defs>
  <g class="base" clip-path="url(#men-clip)">
    <path class="deco scalp" d="M {X0} 0 L {X1} 0 L {X1} 20 L {X0} 20 Z"/>
    <path data-ref="skull" d="M {X0} 20 L {X1} 20 L {X1} 94 L {X0} 94 Z"/>
    <g class="deco diploe">{''.join(holes)}</g>
    <path class="deco tables" d="M {X0} 38 L {X1} 38 M {X0} 78 L {X1} 78"/>
    <path data-ref="dura-mater" d="M {X0} 94 L {X1} 94 L {X1} 126 L {X0} 126 Z"/>
    <path class="deco dura-split" d="M {X0} 110 L {X1} 110"/>
    <path data-ref="subarachnoid-space" data-fill="var(--sys-ventricles)" data-tone="2" d="{subarach}"/>
    <path class="deco trabeculae" d="{' '.join(trab)}"/>
    <g class="deco vessel">{''.join(vessels)}</g>
    <path data-ref="arachnoid-membrane" data-fill="#efe6f5" d="M {X0} 126 L {X1} 126 L {X1} {ARACH} L {X0} {ARACH} Z"/>
    <path data-ref="cerebral-cortex" d="{under(pia)}"/>
    <g class="deco stipple">{''.join(cells)}</g>
    <path data-ref="white-matter" data-fill="var(--sys-white-matter)" d="{under(white_top)}"/>
    <path data-ref="pia-mater" class="line-hotspot pia" data-fill="#d16a8a" d="{pia_line}"/>
  </g>
  <g class="base">
    <g class="labels lbl-base">
      <text class="small deco-label" x="545" y="14">Scalp</text>
      <text data-label-for="skull" x="545" y="62">Skull</text>
      <text data-label-for="dura-mater" x="545" y="114">Dura mater</text>
      <text data-label-for="arachnoid-membrane" x="545" y="140">Arachnoid membrane</text>
      <text data-label-for="subarachnoid-space" x="545" y="178">Subarachnoid space (CSF)</text>
      <text data-label-for="pia-mater" x="545" y="216">Pia mater</text>
      <line data-label-for="pia-mater" class="leader" x1="543" y1="212" x2="{X1 + 2}" y2="{f(surface(X1 - 2))}"/>
      <text data-label-for="cerebral-cortex" x="545" y="262">Cortex (grey matter)</text>
      <text data-label-for="white-matter" x="545" y="352">White matter</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
