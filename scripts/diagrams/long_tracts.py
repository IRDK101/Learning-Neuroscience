from curves import smooth, blob, f, taper, ribbon, mirror

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/long-tracts.svg'
MID = 380

hemi_l = smooth([(372, 40), (300, 30), (210, 50), (150, 110), (140, 180), (170, 230), (240, 262), (330, 262), (372, 240)], closed=True)
hemi_r = smooth(mirror([(372, 40), (300, 30), (210, 50), (150, 110), (140, 180), (170, 230), (240, 262), (330, 262), (372, 240)], MID), closed=True)
s1 = smooth([(168, 92), (200, 58), (250, 40), (262, 56), (222, 76), (190, 108)], closed=True)
m1 = smooth([(268, 38), (330, 34), (366, 44), (364, 62), (326, 54), (274, 56)], closed=True)
thal_l = blob(322, 210, 34, 24, 0.05, seed=1)
thal_r = blob(2 * MID - 322, 210, 34, 24, 0.05, seed=1)
vpl = blob(304, 216, 14, 11, 0.05, seed=2)
caps = 'M 300 70 C 320 120 330 170 350 270 M 460 70 C 440 120 430 170 410 270'

midbrain = smooth([(332, 262), (428, 262), (424, 340), (336, 340)], closed=True)
pons = smooth([(330, 340), (380, 334), (430, 340), (446, 376), (430, 412), (380, 418), (330, 412), (314, 376)], closed=True)
medulla = smooth([(340, 414), (420, 414), (414, 470), (402, 520), (358, 520), (346, 470)], closed=True)
dcn = blob(398, 462, 9, 7, 0.05, seed=3)
cord_tube = smooth([(358, 518), (402, 518), (404, 560), (356, 560)], closed=True)

CS = (MID, 640)
cord = blob(CS[0], CS[1], 96, 64, 0.03, n=12, seed=4)
gm = smooth([(MID, 620), (360, 606), (340, 588), (334, 600), (352, 628), (330, 670), (346, 684), (MID, 664), (414, 684), (430, 670),
             (408, 628), (426, 600), (420, 588), (400, 606)], closed=True)
drg = blob(540, 588, 20, 14, 0.06, seed=5)
droot = ribbon([(420, 600), (470, 590), (520, 588)], [10, 11, 12])
vroot = ribbon([(420, 672), (480, 686), (560, 700)], [10, 11, 12])
skin = blob(676, 598, 30, 24, 0.1, seed=7, rot=-10)
muscle = blob(660, 710, 36, 20, 0.08, seed=6, rot=10)

# pathway paths (one per layer), all for the RIGHT side of the body
touch = smooth([(668, 594), (590, 590), (540, 588), (470, 592), (410, 600), (398, 560), (398, 500), (398, 464)]) + ' ' + \
    smooth([(396, 462), (372, 448), (362, 420), (360, 360), (346, 300), (314, 220), (250, 140), (214, 80)])
pain = smooth([(670, 606), (590, 600), (540, 592), (470, 598), (420, 612), (394, 628), (358, 638), (344, 618), (348, 580), (354, 540),
               (354, 470), (350, 400), (340, 320), (318, 230), (262, 150), (226, 88)])
motor = smooth([(320, 48), (334, 110), (352, 200), (360, 280), (364, 380), (366, 460), (384, 500), (404, 530), (412, 570), (420, 640),
                (410, 668), (480, 688), (560, 702), (630, 710)])

