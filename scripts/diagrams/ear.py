"""Generates content/diagrams/ear.svg: the right ear in a front (coronal) section: outer, middle and inner ear."""
import math
from pathlib import Path
from curves import smooth, blob, f, taper, ribbon

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/ear.svg'

head = smooth([(150, 40), (176, 120), (170, 200), (168, 300), (176, 380), (160, 500)]) + ' L 900 500 L 900 40 Z'
bone = smooth([(260, 70), (420, 60), (640, 80), (760, 130), (790, 260), (760, 400), (640, 470), (420, 478), (280, 440), (236, 330),
               (238, 200)], closed=True)

pinna = smooth([(168, 168), (138, 118), (104, 74), (70, 60), (46, 86), (44, 150), (58, 222), (70, 290), (58, 350), (66, 398),
                (98, 410), (132, 380), (170, 336)], closed=True)
helix = smooth([(150, 160), (116, 108), (80, 86), (64, 110), (66, 170), (80, 230), (88, 290), (82, 340)])
concha = smooth([(168, 222), (130, 214), (108, 240), (114, 276), (140, 296), (170, 290)])

canal_top = [(166, 236), (220, 240), (290, 232), (334, 220)]
canal_bot = [(166, 286), (222, 288), (292, 284), (344, 300)]
canal = smooth(canal_top) + ' L 344 300 ' + smooth(list(reversed(canal_bot)), move=False) + ' Z'
drum = 'M 334 220 C 346 236 352 270 344 300 C 338 284 334 250 334 220 Z'

middle = smooth([(342, 210), (360, 180), (400, 168), (428, 186), (436, 230), (436, 300), (424, 330), (400, 340), (360, 326),
                 (346, 300), (350, 260)], closed=True)

malleus = taper([(342, 282), (346, 250), (352, 222), (360, 200)], 7, 9) + ' ' + blob(364, 192, 12, 10, 0.06, seed=1, rot=-20)
incus = blob(386, 194, 13, 11, 0.07, seed=2, rot=10) + ' ' + taper([(388, 200), (394, 222), (396, 244)], 8, 5)
stapes = ('M 396 246 C 400 240 408 236 420 236 L 424 236 L 424 270 L 420 270 C 408 270 400 264 396 258 Z '
          'M 404 250 C 408 246 414 244 418 244 L 418 262 C 414 262 408 260 404 256 Z')
oval = 'M 425 232 C 432 238 432 268 425 274 C 428 262 428 244 425 232 Z'
roundw = blob(434, 312, 6, 11, 0.04, seed=3)

# cochlea: a tapering tube wound 2.5 turns around (548, 318)
CC = (548, 318)
spiral, widths = [], []
N = 90
for i in range(N + 1):
    t = i / N
    th = math.pi * 1.12 + t * 2 * math.pi * 2.3
    r = 76 * (1 - 0.8 * t)
    spiral.append((CC[0] + r * math.cos(th), CC[1] + r * 0.88 * math.sin(th)))
    widths.append(34 * (1 - 0.6 * t))
cochlea = ribbon(spiral, widths)
cochlea_mid = smooth(spiral[2:-4])

# vestibule (otolith organs) and the three semicircular canals
vestibule = blob(482, 246, 30, 22, 0.08, seed=4, rot=-15)

def ring(cx, cy, rx, ry, rot, th):
    a = math.radians(rot)
    def pts(r1, r2):
        out = []
        for k in range(18):
            u = 2 * math.pi * k / 18
            x, y = r1 * math.cos(u), r2 * math.sin(u)
            out.append((cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)))
        return out
    return smooth(pts(rx, ry), closed=True) + ' ' + smooth(list(reversed(pts(rx - th, ry - th))), closed=True)

canals = ' '.join([ring(492, 156, 36, 56, -6, 11), ring(560, 200, 56, 34, 22, 11), ring(452, 206, 34, 24, 4, 10)])

nerve = ' '.join([taper([(CC[0] + 6, CC[1] - 6), (600, 300), (660, 284), (730, 270), (800, 262)], 12, 22),
                  taper([(486, 238), (540, 250), (610, 268), (680, 272)], 10, 14)])

eust = taper([(404, 330), (440, 380), (490, 430), (560, 490)], 20, 14)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="20 30 860 480" class="shade-sm" role="img" aria-label="The ear in cross-section: outer, middle and inner ear">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/ear.py (edit that, not this).
       Right ear seen from the front, not to scale: the middle and inner ear are enlarged. -->
  <g class="base">
    <path class="deco tissue" style="--dc: color-mix(in srgb, var(--sys-body) 45%, var(--bg-elev))" d="{head}"/>
    <path class="deco tissue" style="--dc: var(--sys-bone)" d="{bone}"/>
    <path data-ref="pinna" data-fill="#e3b7a0" d="{pinna}"/>
    <path class="deco pinna-fold" d="{helix} {concha}"/>
    <path data-ref="auditory-canal" data-fill="#eadfd8" class="no-shade" d="{canal}"/>
    <path data-ref="middle-ear" data-fill="#e2ebf4" class="no-shade" d="{middle}"/>
    <path data-ref="eustachian-tube" data-fill="#e2ebf4" d="{eust}"/>
    <path data-ref="tympanic-membrane" data-fill="#c9879f" d="{drum}"/>
    <path data-ref="malleus" data-fill="var(--sys-bone)" d="{malleus}"/>
    <path data-ref="incus" data-fill="var(--sys-bone)" d="{incus}"/>
    <path data-ref="stapes" data-fill="var(--sys-bone)" d="{stapes}" fill-rule="evenodd"/>
    <path data-ref="semicircular-canals" d="{canals}" fill-rule="evenodd"/>
    <path data-ref="otolith-organs" data-tone="2" d="{vestibule}"/>
    <path data-ref="auditory-nerve" d="{nerve}"/>
    <path data-ref="cochlea" d="{cochlea}"/>
    <path class="deco cochlea-mid" d="{cochlea_mid}"/>
    <path data-ref="oval-window" data-fill="#7d5a91" d="{oval}"/>
    <path data-ref="round-window" data-fill="#7d5a91" d="{roundw}"/>

    <g class="labels lbl-base">
      <text class="deco-label small" x="66" y="470">Outer ear</text>
      <text class="deco-label small" x="352" y="470">Middle ear</text>
      <text class="deco-label small" x="606" y="470">Inner ear</text>
      <text data-label-for="pinna" x="30" y="50">Pinna</text>
      <text data-label-for="auditory-canal" x="186" y="330">Auditory canal</text>
      <line data-label-for="auditory-canal" class="leader" x1="230" y1="314" x2="240" y2="278"/>
      <text text-anchor="end" data-label-for="tympanic-membrane" x="300" y="130">Tympanic membrane</text>
      <line data-label-for="tympanic-membrane" class="leader" x1="296" y1="136" x2="338" y2="228"/>
      <text text-anchor="end" data-label-for="malleus" x="300" y="100">Malleus</text>
      <line data-label-for="malleus" class="leader" x1="302" y1="98" x2="358" y2="190"/>
      <text text-anchor="end" data-label-for="incus" x="370" y="70">Incus</text>
      <line data-label-for="incus" class="leader" x1="372" y1="72" x2="386" y2="184"/>
      <text text-anchor="end" data-label-for="stapes" x="330" y="380">Stapes</text>
      <line data-label-for="stapes" class="leader" x1="332" y1="374" x2="408" y2="262"/>
      <text data-label-for="oval-window" x="640" y="430">Oval window</text>
      <line data-label-for="oval-window" class="leader" x1="638" y1="426" x2="428" y2="262"/>
      <text text-anchor="end" data-label-for="round-window" x="380" y="410">Round window</text>
      <line data-label-for="round-window" class="leader" x1="382" y1="404" x2="432" y2="320"/>
      <text text-anchor="end" data-label-for="eustachian-tube" x="470" y="498">Eustachian tube</text>
      <line data-label-for="eustachian-tube" class="leader" x1="474" y1="490" x2="500" y2="446"/>
      <text data-label-for="semicircular-canals" x="560" y="74">Semicircular canals</text>
      <line data-label-for="semicircular-canals" class="leader" x1="558" y1="80" x2="520" y2="122"/>
      <text data-label-for="otolith-organs" x="640" y="150">Utricle and saccule</text>
      <line data-label-for="otolith-organs" class="leader" x1="638" y1="154" x2="492" y2="236"/>
      <text data-label-for="cochlea" x="640" y="390">Cochlea</text>
      <line data-label-for="cochlea" class="leader" x1="638" y1="384" x2="596" y2="356"/>
      <text data-label-for="auditory-nerve" x="700" y="236">Auditory-vestibular nerve</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
