"""Generates content/diagrams/eye.svg: the right eye cut horizontally, front (cornea) on the left."""
import math
from pathlib import Path
from curves import smooth, blob, f, taper, poly_d

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/eye.svg'
C = (430, 250)

def P(a, r):
    return (C[0] + r * math.cos(math.radians(a)), C[1] + r * math.sin(math.radians(a)))

def arc(a0, a1, r, n=40):
    return [P(a0 + (a1 - a0) * k / n, r) for k in range(n + 1)]

sclera = poly_d(arc(-150, 150, 182) + list(reversed(arc(-150, 150, 170))))
vitreous = poly_d(arc(-150, 150, 170))
retina = poly_d(arc(-118, 118, 168) + list(reversed(arc(-118, 118, 157))))
choroid = poly_d(arc(-122, 122, 170) + list(reversed(arc(-122, 122, 167))))

L_top, L_bot = P(-150, 176), P(150, 176)
cornea_out = [L_top, (244, 196), (226, 250), (244, 304), L_bot]
cornea_in = [(L_top[0] + 4, L_top[1] + 8), (254, 200), (237, 250), (254, 300), (L_bot[0] + 4, L_bot[1] - 8)]
cornea = smooth(cornea_out) + ' L ' + ' L '.join(f'{f(x)} {f(y)}' for x, y in reversed(cornea_in)) + ' Z'
aqueous = smooth(cornea_in) + ' L 300 330 L 300 170 Z'

iris_top = smooth([(276, 168), (296, 172), (300, 200), (298, 226), (290, 228), (286, 200), (280, 176)], closed=True)
iris_bot = smooth([(276, 332), (296, 328), (300, 300), (298, 274), (290, 272), (286, 300), (280, 324)], closed=True)
pupil = 'M 290 228 L 298 228 L 298 272 L 290 272 Z'
lens = blob(322, 250, 25, 60, 0.0, n=12)
cil_top = smooth([(314, 136), (334, 126), (340, 156), (328, 174), (316, 162)], closed=True)
cil_bot = smooth([(314, 364), (334, 374), (340, 344), (328, 326), (316, 338)], closed=True)
zonules = ' '.join(f'M 330 {y0} L {x1} {y1}' for y0, x1, y1 in [(172, 314, 196), (174, 322, 191), (176, 330, 196), (328, 314, 304), (326, 322, 309), (324, 330, 304)])

fov = P(-2, 157)
fovea = f'M {f(fov[0] - 12)} {f(fov[1] - 6)} C {f(fov[0] - 4)} {f(fov[1] - 4)} {f(fov[0] + 4)} {f(fov[1] + 8)} {f(fov[0] + 10)} {f(fov[1] + 10)} L {f(fov[0] + 14)} {f(fov[1] - 4)} C {f(fov[0] + 6)} {f(fov[1] - 8)} {f(fov[0] - 4)} {f(fov[1] - 10)} {f(fov[0] - 12)} {f(fov[1] - 6)} Z'
disk_c = P(18, 162)
optic_disk = blob(disk_c[0], disk_c[1], 8, 15, 0.02, seed=1, rot=18)
macula = blob(fov[0] - 3, fov[1], 5, 20, 0.02, seed=2)
nerve = taper([(disk_c[0] - 4, disk_c[1]), (650, 318), (720, 346), (800, 372)], 40, 46)
vessels = ' '.join(smooth([(disk_c[0] - 6, disk_c[1] + dy * 0.2), P(a1, 160), P(a2, 160)]) for dy, a1, a2 in [(-10, -20, -60), (8, 40, 80), (-4, -10, -40), (6, 30, 100)])

mus_top = taper([(470, 76), (540, 64), (640, 74), (760, 104), (840, 130)], 22, 30)
mus_bot = taper([(470, 424), (540, 436), (640, 426), (760, 396), (840, 370)], 22, 30)
conj = smooth([P(-150, 184), P(-135, 186), (330, 50), (360, 40)]) + ' ' + smooth([P(150, 184), P(135, 186), (330, 450), (360, 460)])

rays = ' '.join(f'M 40 {y} L 230 {y + (250 - y) * 0.15} L 320 {f(250 + (y - 250) * 0.55)} L {f(fov[0] - 4)} {f(fov[1])}' for y in (196, 304))

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="20 20 860 470" class="shade-lg" role="img" aria-label="The eye cut horizontally, showing its parts from cornea to optic nerve">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/eye.py (edit that, not this).
       Right eye seen from above; light enters on the left. -->
  <g class="base">
    <path data-ref="extraocular-muscles" data-fill="#c8705f" d="{mus_top} {mus_bot}"/>
    <path data-ref="optic-nerve" d="{nerve}"/>
    <path data-ref="vitreous-humor" data-fill="#eef4fa" class="no-shade" d="{vitreous}"/>
    <path class="deco tissue" style="--dc: #8a5a4a" d="{choroid}"/>
    <path data-ref="retina" data-fill="#e3a2a2" d="{retina}"/>
    <path data-ref="macula" data-fill="#e6c27a" class="no-shade" d="{macula}"/>
    <path data-ref="fovea" data-fill="#9a4f3c" d="{fovea}"/>
    <path data-ref="optic-disk" data-fill="#f3e2b8" d="{optic_disk}"/>
    <path data-ref="sclera" data-fill="#f4f1ea" d="{sclera}"/>
    <path data-ref="aqueous-humor" data-fill="#dfeef8" class="no-shade" d="{aqueous}"/>
    <path data-ref="ciliary-muscle" data-fill="#c8705f" d="{cil_top} {cil_bot}"/>
    <path data-ref="zonule-fibers" class="line-hotspot fine" data-fill="#9aa3ad" d="{zonules}"/>
    <path data-ref="lens" data-fill="#cfe2ef" d="{lens}"/>
    <path data-ref="iris" data-fill="#4f86a8" d="{iris_top} {iris_bot}"/>
    <path data-ref="pupil" data-fill="#1d2433" class="no-shade" d="{pupil}"/>
    <path data-ref="cornea" data-fill="#bcdcef" d="{cornea}"/>
    <path data-ref="conjunctiva" class="line-hotspot fine" data-fill="#d98d9a" d="{conj}"/>
    <path class="deco light-ray" d="{rays}"/>

    <g class="labels lbl-base">
      <text data-label-for="cornea" x="40" y="160">Cornea</text>
      <line data-label-for="cornea" class="leader" x1="96" y1="164" x2="236" y2="220"/>
      <text data-label-for="aqueous-humor" x="40" y="390">Aqueous humor</text>
      <line data-label-for="aqueous-humor" class="leader" x1="110" y1="380" x2="268" y2="276"/>
      <text data-label-for="pupil" x="40" y="350">Pupil</text>
      <line data-label-for="pupil" class="leader" x1="84" y1="344" x2="292" y2="262"/>
      <text text-anchor="end" data-label-for="iris" x="250" y="106">Iris</text>
      <line data-label-for="iris" class="leader" x1="252" y1="110" x2="292" y2="190"/>
      <text text-anchor="end" data-label-for="conjunctiva" x="250" y="64">Conjunctiva</text>
      <line data-label-for="conjunctiva" class="leader" x1="252" y1="66" x2="330" y2="52"/>
      <text text-anchor="middle" data-label-for="ciliary-muscle" x="330" y="440">Ciliary muscle</text>
      <line data-label-for="ciliary-muscle" class="leader" x1="324" y1="426" x2="320" y2="372"/>
      <text text-anchor="middle" data-label-for="zonule-fibers" x="450" y="356">Zonule fibers</text>
      <line data-label-for="zonule-fibers" class="leader" x1="400" y1="346" x2="330" y2="318"/>
      <text text-anchor="middle" data-label-for="lens" x="390" y="196">Lens</text>
      <line data-label-for="lens" class="leader" x1="380" y1="202" x2="344" y2="226"/>
      <text text-anchor="middle" data-label-for="vitreous-humor" x="460" y="250">Vitreous humor</text>
      <text data-label-for="retina" x="660" y="190">Retina</text>
      <line data-label-for="retina" class="leader" x1="658" y1="186" x2="586" y2="180"/>
      <text data-label-for="sclera" x="560" y="40">Sclera</text>
      <line data-label-for="sclera" class="leader" x1="572" y1="46" x2="540" y2="110"/>
      <text data-label-for="fovea" x="660" y="230">Fovea</text>
      <line data-label-for="fovea" class="leader" x1="658" y1="228" x2="594" y2="244"/>
      <text data-label-for="macula" x="660" y="262">Macula</text>
      <line data-label-for="macula" class="leader" x1="658" y1="258" x2="590" y2="258"/>
      <text data-label-for="optic-disk" x="520" y="410">Optic disk (blind spot)</text>
      <line data-label-for="optic-disk" class="leader" x1="580" y1="396" x2="584" y2="312"/>
      <text data-label-for="optic-nerve" x="760" y="420">Optic nerve</text>
      <text data-label-for="extraocular-muscles" x="660" y="50">Extraocular muscle</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
