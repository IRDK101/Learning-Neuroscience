"""Generates content/diagrams/olfaction.svg: olfactory epithelium, cribriform plate and olfactory bulb.
Receptor cells of the same type (same color) all send their axons to the same glomerulus."""
from pathlib import Path
from curves import smooth, blob, f, taper, spindle, bow

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/olfaction.svg'
TYPE_COL = {'a': '#3f7fd0', 'b': '#e08a2e', 'c': '#2a9d8f'}
XS = [150, 222, 294, 366, 438, 510, 582, 654]
TYPES = ['a', 'b', 'c', 'a', 'c', 'b', 'a', 'c']
GLOM = {'a': (250, 186), 'b': (440, 186), 'c': (620, 186)}

cells, nucs, axons, cilia = [], [], [], []
for i, (x, t) in enumerate(zip(XS, TYPES)):
    cells.append(f'<path style="fill: {TYPE_COL[t]}" d="{spindle(bow((x, 396), (x, 312), 3 if i % 2 else -3, n=7), 18, 4)}"/>')
    nucs.append(f'<ellipse cx="{x + (1 if i % 2 else -1)}" cy="356" rx="4" ry="7"/>')
    g = GLOM[t]
    axons.append(f'<path style="fill: {TYPE_COL[t]}" d="{taper([(x, 314), (x, 284), (x + (g[0] - x) * 0.35, 246), (g[0] + (x - g[0]) * 0.1, 204)], 3.2, 2.4)}"/>')
    for dx in (-6, -2, 3, 7):
        cilia.append(f'M {x} 396 C {x + dx} 410 {x + dx * 2.2} 418 {x + dx * 3} 430')

support = ''.join(f'<path d="{spindle([(x, 398), (x + 2, 356), (x, 308)], 22, 10)}"/>' for x in [186, 258, 330, 402, 474, 546, 618])
basal = ''.join(f'<path d="{blob(x, 394, 10, 6, 0.08, seed=x)}"/>' for x in [116, 186, 330, 474, 618, 688])

plate = 'M 90 266 L 720 266 L 720 292 L 90 292 Z'
holes = ''.join(f'<rect x="{x - 5}" y="266" width="10" height="26" rx="3"/>' for x in XS)

bulb = smooth([(100, 230), (120, 130), (200, 80), (400, 66), (600, 76), (700, 110), (760, 150), (840, 150), (840, 210), (760, 214),
               (700, 236), (400, 246)], closed=True)
gloms = ''.join(f'<path d="{blob(gx, gy, 26, 20, 0.08, seed=i)}"/>' for i, (gx, gy) in enumerate(GLOM.values()))
gl_type = ''.join(f'<path class="glom-ring" style="stroke: {TYPE_COL[t]}" d="{blob(gx, gy, 20, 14, 0.08, seed=3)}"/>' for t, (gx, gy) in GLOM.items())
mitral = []
for t, (gx, gy) in GLOM.items():
    mx, my = gx + 6, 116
    mitral.append(f'<path d="M {mx - 10} {my + 8} L {mx} {my - 12} L {mx + 10} {my + 8} Z"/>')
    mitral.append(f'<path d="{taper([(mx, my + 8), (gx + 2, my + 40), (gx, gy - 12)], 3.4, 2.2)}"/>')
    mitral.append(f'<path d="{taper([(mx, my - 10), (mx + 30, my - 26), (760, 168), (838, 172)], 2.8, 2.4)}"/>')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="60 40 900 420" class="shade-sm" role="img" aria-label="Olfactory epithelium, cribriform plate and olfactory bulb">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/olfaction.py (edit that, not this).
       Stylized: three receptor types shown in three colors; each type converges on its own glomerulus. -->
  <g class="base">
    <path data-ref="olfactory-bulb" data-fill="#e9c9a0" d="{bulb}"/>
    <path class="deco tissue" style="--dc: #dfeaf4" d="M 90 420 L 720 420 L 720 460 L 90 460 Z"/>
    <path class="deco tissue mucus" style="--dc: #e9f0d2" d="M 90 398 L 720 398 L 720 424 L 90 424 Z"/>
    <path data-ref="olfactory-epithelium" data-tone="2" d="M 90 300 L 720 300 L 720 400 L 90 400 Z"/>
    <g class="deco support-cells">{support}</g>
    <g class="deco support-cells">{basal}</g>
    <path data-ref="olfactory-cilia" class="line-hotspot fine" data-fill="#8a6a2c" d="{' '.join(cilia)}"/>
    <g data-ref="olfactory-receptor-cell">{''.join(cells)}{''.join(axons)}</g>
    <g class="deco cell-nuc">{''.join(nucs)}</g>
    <path data-ref="cribriform-plate" fill-rule="evenodd" d="{plate}"/>
    <g class="deco plate-holes">{holes}</g>
    <g data-ref="glomerulus" data-fill="#c9a7cf">{gloms}</g>
    <g class="deco">{gl_type}</g>
    <g data-ref="mitral-cell" data-fill="#7a5a9a">{''.join(mitral)}</g>

    <g class="labels lbl-base">
      <text data-label-for="olfactory-bulb" x="110" y="64">Olfactory bulb</text>
      <text data-label-for="mitral-cell" x="300" y="64">Mitral cells</text>
      <line data-label-for="mitral-cell" class="leader" x1="330" y1="70" x2="440" y2="112"/>
      <text data-label-for="glomerulus" x="740" y="250">Glomeruli</text>
      <line data-label-for="glomerulus" class="leader" x1="738" y1="246" x2="644" y2="196"/>
      <text data-label-for="cribriform-plate" x="740" y="284">Cribriform plate (bone)</text>
      <text data-label-for="olfactory-receptor-cell" x="740" y="340">Olfactory receptor cells</text>
      <line data-label-for="olfactory-receptor-cell" class="leader" x1="738" y1="336" x2="664" y2="346"/>
      <text data-label-for="olfactory-epithelium" x="740" y="372">Olfactory epithelium</text>
      <text data-label-for="olfactory-cilia" x="740" y="414">Cilia in mucus</text>
      <line data-label-for="olfactory-cilia" class="leader" x1="738" y1="410" x2="680" y2="420"/>
      <text class="small deco-label" x="100" y="448">Nasal cavity (air with odorants)</text>
      <text class="small deco-label" x="770" y="138">To the olfactory cortex</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
