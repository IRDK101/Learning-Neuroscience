"""Generates content/diagrams/cochlea.svg: a cross-section through one turn of the cochlea, with the organ of Corti."""
import math
from pathlib import Path
from curves import smooth, blob, f, taper, poly_d

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/cochlea.svg'
C, R = (380, 270), 214

def arc(a0, a1, n=24):
    return [(C[0] + R * math.cos(math.radians(a0 + (a1 - a0) * k / n)), C[1] + R * math.sin(math.radians(a0 + (a1 - a0) * k / n))) for k in range(n + 1)]

def ang(p):
    return math.degrees(math.atan2(p[1] - C[1], p[0] - C[0]))

A = (214, 246)                      # tip of the spiral limbus (Reissner's membrane starts here)
B = arc(-40, -40, 1)[0]             # Reissner's membrane meets the outer wall
D = arc(20, 20, 1)[0]               # basilar membrane meets the outer wall
E = (250, 336)                      # inner end of the basilar membrane
LT = arc(-172, -172, 1)[0]
LB = arc(166, 166, 1)[0]

sv = poly_d([A] + arc(-40, -172, 40) + [(196, 236)])
sm = poly_d([A] + arc(-40, 20, 20) + [(D[0] - 4, D[1]), (E[0], E[1] - 6), (236, 300), (222, 262)])
st = poly_d([(E[0], E[1] + 8)] + [(D[0] - 2, D[1] + 8)] + arc(22, 166, 40) + [(200, 330)])
reissner = f'M {f(A[0])} {f(A[1])} L {f(B[0])} {f(B[1])}'
basilar = f'M {f(E[0])} {f(E[1] - 2)} L {f(D[0] - 6)} {f(D[1] - 2)} L {f(D[0] - 4)} {f(D[1] + 7)} L {f(E[0])} {f(E[1] + 7)} Z'

wall = blob(C[0], C[1], R + 34, R + 30, 0.02, n=12, seed=2)
modiolus = smooth([(60, 120), (150, 150), (196, 220), (240, 300), (200, 360), (150, 420), (70, 470), (30, 480), (30, 110)], closed=True)

corti = smooth([(272, 334), (296, 306), (330, 290), (380, 282), (440, 286), (488, 306), (512, 334)])
corti_d = corti + ' Z'
tect = smooth([(214, 258), (260, 252), (330, 256), (400, 262), (456, 272), (470, 282), (452, 286), (400, 280), (330, 276), (270, 274), (222, 270)], closed=True)

# hair cells (inner at x=326, outer at 408/434/460)
ihc = smooth([(318, 322), (314, 304), (316, 292), (328, 288), (338, 294), (338, 308), (334, 322)], closed=True)
ohc = ' '.join(f'M {x - 7} 296 L {x + 7} 296 L {x + 7} 324 C {x + 7} 330 {x - 7} 330 {x - 7} 324 Z' for x in (410, 436, 462))
cilia = []
for x, y0, h in [(322, 288, 12), (327, 287, 15), (332, 288, 12)]:
    cilia.append(f'M {x} {y0} L {x + 1} {y0 - h}')
for x in (410, 436, 462):
    for dx, h in ((-4, 10), (0, 13), (4, 16)):
        cilia.append(f'M {x + dx} 296 L {x + dx + 1} {296 - h}')
support = ' '.join(blob(x, 318, 9, 11, 0.06, seed=i) for i, x in enumerate((296, 356, 384, 486)))

# spiral ganglion in the modiolus, fibers out to the hair cells, nerve down and away
gang = ' '.join(blob(x, y, 11, 9, 0.08, seed=i, rot=r) for i, (x, y, r) in enumerate([(128, 298, 20), (108, 318, 10), (146, 320, -10), (122, 340, 0), (150, 344, 15), (104, 350, -5), (130, 366, 8)]))
fibers = ' '.join([taper([(140, 300), (190, 308), (250, 318), (310, 322)], 3.2, 2.4),
                   taper([(148, 322), (200, 326), (300, 330), (400, 328)], 2.6, 2),
                   taper([(150, 330), (220, 334), (330, 334), (436, 330)], 2.6, 2)])
nerve = taper([(126, 340), (118, 390), (98, 440), (76, 500)], 30, 30)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="20 30 860 480" class="shade-sm" role="img" aria-label="Cross-section of the cochlea with the organ of Corti">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/cochlea.py (edit that, not this).
       One turn of the cochlea cut across; the organ of Corti is enlarged. -->
  <g class="base">
    <path class="deco tissue" style="--dc: var(--sys-bone)" d="{wall}"/>
    <path class="deco tissue" style="--dc: var(--sys-bone)" d="{modiolus}"/>
    <path data-ref="scala-vestibuli" data-fill="#d4e3f1" class="no-shade" d="{sv}"/>
    <path data-ref="scala-tympani" data-fill="#d4e3f1" class="no-shade" d="{st}"/>
    <path data-ref="scala-media" data-fill="#e8dcef" class="no-shade" d="{sm}"/>
    <path data-ref="basilar-membrane" data-fill="#8f6fa6" d="{basilar}"/>
    <path data-ref="organ-of-corti" data-tone="2" d="{corti_d}"/>
    <path class="deco support" d="{support}"/>
    <path data-ref="inner-hair-cell" data-fill="#e4b07a" d="{ihc}"/>
    <path data-ref="outer-hair-cell" data-fill="#d79a6a" d="{ohc}"/>
    <path data-ref="stereocilia" class="line-hotspot fine" data-fill="#9a5a2c" d="{' '.join(cilia)}"/>
    <path data-ref="tectorial-membrane" data-fill="#c9b9e0" d="{tect}"/>
    <path data-ref="reissners-membrane" class="line-hotspot fine" data-fill="#8f6fa6" d="{reissner}"/>
    <path data-ref="auditory-nerve" d="{nerve}"/>
    <g data-ref="spiral-ganglion" data-fill="var(--sys-nerve)"><path d="{fibers}"/><path d="{gang}"/></g>

    <g class="labels lbl-base">
      <text text-anchor="middle" data-label-for="scala-vestibuli" x="370" y="120">Scala vestibuli</text>
      <text text-anchor="middle" data-label-for="scala-media" x="500" y="236">Scala media</text>
      <text text-anchor="middle" data-label-for="scala-tympani" x="380" y="420">Scala tympani</text>
      <text data-label-for="reissners-membrane" x="640" y="120">Reissner's membrane</text>
      <line data-label-for="reissners-membrane" class="leader" x1="638" y1="126" x2="480" y2="174"/>
      <text data-label-for="tectorial-membrane" x="640" y="214">Tectorial membrane</text>
      <line data-label-for="tectorial-membrane" class="leader" x1="638" y1="218" x2="450" y2="272"/>
      <text data-label-for="stereocilia" x="640" y="250">Stereocilia</text>
      <line data-label-for="stereocilia" class="leader" x1="638" y1="254" x2="466" y2="284"/>
      <text data-label-for="outer-hair-cell" x="640" y="290">Outer hair cells</text>
      <line data-label-for="outer-hair-cell" class="leader" x1="638" y1="292" x2="470" y2="312"/>
      <text data-label-for="organ-of-corti" x="640" y="330">Organ of Corti</text>
      <line data-label-for="organ-of-corti" class="leader" x1="638" y1="330" x2="500" y2="326"/>
      <text data-label-for="basilar-membrane" x="640" y="370">Basilar membrane</text>
      <line data-label-for="basilar-membrane" class="leader" x1="638" y1="366" x2="520" y2="340"/>
      <text text-anchor="end" data-label-for="inner-hair-cell" x="290" y="216">Inner hair cell</text>
      <line data-label-for="inner-hair-cell" class="leader" x1="284" y1="222" x2="322" y2="296"/>
      <text data-label-for="spiral-ganglion" x="40" y="250">Spiral ganglion</text>
      <line data-label-for="spiral-ganglion" class="leader" x1="80" y1="258" x2="120" y2="296"/>
      <text data-label-for="auditory-nerve" x="100" y="500">Auditory nerve</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
