"""Generates content/diagrams/skin.svg: a block of skin with its layers and the five kinds of sensory endings."""
import math
from pathlib import Path
from curves import smooth, blob, f, taper, poly_d, ribbon

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/skin.svg'
X0, X1 = 60, 660

def surf(x):
    glab = max(0.0, min(1.0, (430 - x) / 120))     # ridged (glabrous) on the left, smoother on the right
    return 82 + glab * 5 * math.sin(x / 11) + (1 - glab) * 2 * math.sin(x / 40)

def dej(x):    # dermal-epidermal junction: dermal papillae poke up
    return 150 - 16 * max(0.0, math.sin((x - 20) / 26)) ** 1.6 + 4 * math.sin(x / 9)

xs = list(range(X0, X1 + 1, 3))
top = [(x, surf(x)) for x in xs]
mid = [(x, dej(x)) for x in xs]
SUB = 340

def low(x):
    return SUB + 10 * math.sin(x / 47)

bot = [(x, low(x)) for x in xs]

epi = poly_d(top + list(reversed(mid)))
derm = poly_d(mid + list(reversed(bot)))
sub = poly_d(bot + [(X1, 490), (X0, 490)])
stratum = poly_d(top + list(reversed([(x, y + 9) for x, y in top])))

# fat lobules in the subcutaneous layer
import random
rnd = random.Random(3)
fat = []
for row, y in enumerate(range(372, 490, 34)):
    for x in range(X0 + 14 + (row % 2) * 22, X1, 44):
        fat.append(f'<path d="{blob(x + rnd.uniform(-4, 4), y + rnd.uniform(-3, 3), 20, 15, 0.1, seed=rnd.randint(0, 9))}"/>')

# blood vessels in the dermis
vessels = 'M 60 300 C 160 280 240 310 330 290 C 420 272 520 300 660 284 M 120 300 C 130 250 150 220 170 190 M 400 284 C 396 240 410 210 430 180'

def axon_down(x_end, y_end, x_bottom, wiggle=0):
    pts = [(x_bottom, 500), (x_bottom + wiggle, 430), ((x_bottom + x_end) / 2, (430 + y_end) / 2 + 20), (x_end, y_end)]
    return taper(pts, 5, 3)

# Meissner corpuscle: an upright capsule in a dermal papilla, with a coiled axon
mx = 150
my = dej(mx) + 20
meissner = blob(mx, my, 11, 22, 0.05, seed=1)
coil = ' '.join(f'M {mx - 8} {f(my - 14 + k * 7)} C {mx - 2} {f(my - 18 + k * 7)} {mx + 4} {f(my - 10 + k * 7)} {mx + 8} {f(my - 14 + k * 7)}' for k in range(5))
meissner_ax = axon_down(mx, my + 20, 130, 6)

# Merkel cells: discs at the base of the epidermis with a branching ending
kx = 262
merkel_cells = ' '.join(blob(kx + dx, dej(kx + dx) - 8, 8, 5, 0.05, seed=i) for i, dx in enumerate((-22, 0, 22)))
merkel_ax = axon_down(kx, dej(kx) + 6, 240, -4) + ' ' + ' '.join(taper([(kx, dej(kx) + 6), (kx + dx * 0.6, dej(kx) + 2), (kx + dx, dej(kx + dx) - 2)], 3, 2) for dx in (-22, 22))

# Free nerve endings: branches up into the epidermis
fx = 352
free = axon_down(fx, dej(fx) + 20, 330, 4) + ' ' + ' '.join(
    taper([(fx, dej(fx) + 20), (fx + dx * 0.5, dej(fx) - 6), (fx + dx, surf(fx + dx) + 22)], 3, 1.4) for dx in (-26, -8, 12, 30))

# Ruffini ending: a horizontal spindle capsule in the deep dermis
rx, ry = 456, 250
ruffini = ribbon([(rx - 34, ry), (rx - 18, ry - 3), (rx, ry - 4), (rx + 18, ry - 3), (rx + 34, ry)], [4, 14, 16, 14, 4])
ruffini_branch = ' '.join(f'M {rx - 22 + k * 9} {ry - 2} l 3 -4 l 3 4' for k in range(5))
ruffini_ax = axon_down(rx - 30, ry + 2, 430, 6)

# Pacinian corpuscle: a big onion of rings at the dermis/fat border
px, py = 566, 372
pac_outer = blob(px, py, 26, 40, 0.03, seed=2, rot=8)
rings = ''.join(f'<ellipse cx="{px}" cy="{py}" rx="{26 - k * 4.5}" ry="{40 - k * 7}" transform="rotate(8 {px} {py})"/>' for k in range(1, 5))
pac_ax = axon_down(px + 2, py + 30, 590, 2)
pac_core = f'M {px} {py + 34} L {px - 3} {py - 16}'

# hair with follicle (hairy skin on the right)
hx = 640
hair = f'M {hx - 30} 30 C {hx - 20} 50 {hx - 10} 66 {hx - 4} 84 L {hx + 4} 250'
follicle = smooth([(hx - 12, 86), (hx - 10, 180), (hx - 14, 240), (hx - 6, 262), (hx + 14, 262), (hx + 20, 240), (hx + 14, 180), (hx + 12, 86)])

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="20 20 880 490" class="shade-sm" role="img" aria-label="Skin in cross-section with its layers and touch, pain and temperature receptors">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/skin.py (edit that, not this).
       Hairless (glabrous) skin on the left, hairy skin on the right; receptors are enlarged. -->
  <defs><clipPath id="skin-clip"><rect x="{X0}" y="20" width="{X1 - X0}" height="480"/></clipPath></defs>
  <g class="base" clip-path="url(#skin-clip)">
    <path data-ref="subcutaneous-layer" data-fill="#f0dca8" d="{sub}"/>
    <g class="deco fat">{''.join(fat)}</g>
    <path data-ref="dermis" data-fill="#efc1b0" d="{derm}"/>
    <path class="deco vessels-deco" d="{vessels}"/>
    <path data-ref="epidermis" data-fill="#e8b49a" d="{epi}"/>
    <path class="deco stratum" d="{stratum}"/>
    <path class="deco follicle" d="{follicle}"/>
    <path class="deco hair" d="{hair}"/>

    <g data-ref="meissner-corpuscle"><path d="{meissner_ax}"/><path d="{meissner}"/></g>
    <path class="deco coil" d="{coil}"/>
    <g data-ref="merkel-cell"><path d="{merkel_ax}"/><path style="fill: #8fa9cc" d="{merkel_cells}"/></g>
    <path data-ref="free-nerve-ending" data-fill="#d8b23a" d="{free}"/>
    <g data-ref="ruffini-ending"><path d="{ruffini_ax}"/><path d="{ruffini}"/></g>
    <path class="deco coil" d="{ruffini_branch}"/>
    <g data-ref="pacinian-corpuscle"><path d="{pac_ax}"/><path d="{pac_outer}"/></g>
    <g class="deco capsule-rings">{rings}</g>
    <path class="deco coil" d="{pac_core}"/>
  </g>
  <g class="base">
    <g class="labels lbl-base">
      <text data-label-for="epidermis" x="680" y="118">Epidermis</text>
      <text data-label-for="dermis" x="680" y="250">Dermis</text>
      <text data-label-for="subcutaneous-layer" x="680" y="420">Subcutaneous layer</text>
      <text text-anchor="middle" data-label-for="meissner-corpuscle" x="150" y="62">Meissner corpuscle</text>
      <line data-label-for="meissner-corpuscle" class="leader" x1="150" y1="68" x2="150" y2="150"/>
      <text text-anchor="middle" data-label-for="merkel-cell" x="282" y="236">Merkel cells</text>
      <line data-label-for="merkel-cell" class="leader" x1="270" y1="222" x2="262" y2="150"/>
      <text text-anchor="middle" data-label-for="free-nerve-ending" x="370" y="62">Free nerve endings</text>
      <line data-label-for="free-nerve-ending" class="leader" x1="364" y1="68" x2="360" y2="108"/>
      <text text-anchor="middle" data-label-for="ruffini-ending" x="470" y="214">Ruffini ending</text>
      <text data-label-for="pacinian-corpuscle" x="476" y="470">Pacinian corpuscle</text>
      <line data-label-for="pacinian-corpuscle" class="leader" x1="540" y1="456" x2="560" y2="412"/>
      <text class="small deco-label" x="64" y="36">Hairless skin</text>
      <text class="small deco-label" x="560" y="36">Hairy skin</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
