"""Generates content/diagrams/retina.svg: the layers of the retina. Light comes from the top; the photoreceptors face away from it."""
from pathlib import Path
from curves import smooth, blob, f, taper, spindle, bow

OUT = Path(__file__).resolve().parents[2] / 'content/diagrams/retina.svg'

XS = [110, 175, 240, 305, 370, 435, 500]
KIND = ['rod', 'cone', 'rod', 'cone', 'rod', 'cone', 'rod']

rods, cones, disks, pr_nuc = [], [], [], []
for x, k in zip(XS, KIND):
    body = f'M {x - 3} 300 L {x + 3} 300 L {x + 3} 330 L {x - 3} 330 Z'      # axon to the terminal
    foot = blob(x, 298, 7, 5, 0.04, seed=x)
    soma = blob(x, 344, 9, 13, 0.05, seed=x + 1)
    inner = f'M {x - 7} 356 L {x + 7} 356 L {x + 8} 396 L {x - 8} 396 Z'
    if k == 'rod':
        outer = f'M {x - 6} 398 L {x + 6} 398 L {x + 6} 462 C {x + 6} 468 {x - 6} 468 {x - 6} 462 Z'
        rods.append(f'<path d="{body} {foot} {soma} {inner} {outer}"/>')
        disks.append(' '.join(f'M {x - 5} {y} L {x + 5} {y}' for y in range(404, 462, 6)))
    else:
        outer = f'M {x - 9} 398 L {x + 9} 398 L {x + 2} 440 L {x - 2} 440 Z'
        cones.append(f'<path d="{body} {foot} {soma} {inner} {outer}"/>')
        disks.append(' '.join(f'M {x - (8 - (y - 400) * 0.16):.1f} {y} L {x + (8 - (y - 400) * 0.16):.1f} {y}' for y in range(404, 438, 6)))
    pr_nuc.append(f'<ellipse cx="{x}" cy="344" rx="5" ry="7"/>')

# bipolar cells: each gathers two or three photoreceptors and feeds one ganglion cell
BIP = [(142, [110, 175]), (272, [240, 305]), (420, [370, 435, 500])]
GAN = [142, 272, 420]
bip, gan, gan_nuc, bip_nuc = [], [], [], []
for (bx, srcs), gx in zip(BIP, GAN):
    bip.append(spindle(bow((bx, 278), (bx, 196), 4, n=7), 16, 3))
    for sx in srcs:
        bip.append(taper([(bx, 276), ((bx + sx) / 2, 284), (sx, 292)], 3, 2))
    bip.append(taper([(bx, 198), (bx + 2, 170), (gx, 142)], 3.4, 2.6))
    bip_nuc.append(f'<ellipse cx="{bx}" cy="238" rx="4.5" ry="7"/>')
    gan.append(blob(gx, 124, 17, 14, 0.06, seed=gx))
    gan.append(taper([(gx, 112), (gx + 6, 96), (gx + 30, 82), (640, 74 + GAN.index(gx) * 6)], 5, 4))
    gan_nuc.append(f'<circle cx="{gx}" cy="124" r="6"/>')

horiz = blob(300, 288, 30, 9, 0.05, seed=3) + ' ' + ' '.join(taper([(300 + d * 0.3, 288), (300 + d * 0.7, 290), (300 + d, 296)], 4, 2) for d in (-190, -125, -60, 70, 135, 200))
amac = blob(352, 186, 22, 9, 0.05, seed=4) + ' ' + ' '.join(taper([(352 + d * 0.3, 180), (352 + d * 0.7, 168), (352 + d, 158)], 3.6, 2) for d in (-210, -80, 68))

pigment = smooth([(70, 470), (200, 466), (360, 470), (540, 466)]) + ' L 540 500 L 70 500 Z'
granules = ''.join(f'<circle cx="{x}" cy="{484 + (x % 3) * 4}" r="2.2"/>' for x in range(80, 540, 11))

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="20 20 860 490" class="shade-sm" role="img" aria-label="The layers of the retina, from ganglion cells to photoreceptors and pigmented epithelium">
  <!-- Original drawing for NeuroMap, generated by scripts/diagrams/retina.py (edit that, not this).
       Light enters from the top and passes through the other layers before reaching the photoreceptors. -->
  <defs>
    <marker id="ret-arrow" class="arrow arrow-light" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0,0 L10,5 L0,10 z"/></marker>
  </defs>
  <g class="base">
    <rect class="deco tissue" style="--dc: color-mix(in srgb, var(--sys-eye) 14%, var(--bg-elev))" x="70" y="40" width="470" height="430" rx="6"/>
    <path data-ref="pigmented-epithelium" data-fill="#6d4a3a" d="{pigment}"/>
    <g class="deco pigment-dots">{granules}</g>
    <g data-ref="rod" data-fill="#8fa9cc">{''.join(rods)}</g>
    <g data-ref="cone" data-fill="#d98f6a">{''.join(cones)}</g>
    <path class="deco disks" d="{' '.join(disks)}"/>
    <g class="deco cell-nuc">{''.join(pr_nuc)}</g>
    <path data-ref="horizontal-cell" data-fill="#7fb59a" d="{horiz}"/>
    <path data-ref="bipolar-cell" data-fill="#b48ead" d="{' '.join(bip)}"/>
    <g class="deco cell-nuc">{''.join(bip_nuc)}</g>
    <path data-ref="amacrine-cell" data-fill="#d8b23a" d="{amac}"/>
    <path data-ref="ganglion-cell" data-fill="#5b7fb8" d="{' '.join(gan)}"/>
    <g class="deco cell-nuc">{''.join(gan_nuc)}</g>
    <path class="deco light-ray" marker-end="url(#ret-arrow)" d="M 50 40 L 50 200"/>

    <g class="labels lbl-base">
      <text class="small deco-label" x="34" y="230">Light</text>
      <text data-label-for="ganglion-cell" x="560" y="128">Ganglion cells</text>
      <line data-label-for="ganglion-cell" class="leader" x1="558" y1="124" x2="438" y2="124"/>
      <text class="small deco-label" x="600" y="104">To the optic nerve</text>
      <text data-label-for="amacrine-cell" x="560" y="176">Amacrine cell</text>
      <line data-label-for="amacrine-cell" class="leader" x1="558" y1="172" x2="420" y2="160"/>
      <text data-label-for="bipolar-cell" x="560" y="240">Bipolar cells</text>
      <line data-label-for="bipolar-cell" class="leader" x1="558" y1="236" x2="430" y2="236"/>
      <text data-label-for="horizontal-cell" x="560" y="296">Horizontal cell</text>
      <line data-label-for="horizontal-cell" class="leader" x1="558" y1="292" x2="500" y2="296"/>
      <text data-label-for="cone" x="560" y="400">Cones</text>
      <line data-label-for="cone" class="leader" x1="558" y1="396" x2="444" y2="410"/>
      <text data-label-for="rod" x="560" y="440">Rods</text>
      <line data-label-for="rod" class="leader" x1="558" y1="436" x2="507" y2="436"/>
      <text data-label-for="pigmented-epithelium" x="560" y="490">Pigmented epithelium</text>
    </g>
  </g>
</svg>
'''
OUT.write_text(svg)
print('wrote', OUT)
